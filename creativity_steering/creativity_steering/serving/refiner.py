"""Concept-frozen OpenAI refiner for the steer -> refine pipeline.

The steered 14B supplies a *diverse* set of candidate ideas; this refiner uses a frontier OpenAI
model to polish each one for clarity and concrete specificity — WITHOUT changing concepts, merging,
dropping, reordering, or homogenizing. Free rewrite erases the steered diversity (the pipeline
architecture doc forbids per-idea rewrite, and the Diversity-Sprint Family-6 finding backs it), so
the system prompt hard-constrains the model to a wording pass only.

Offline-testable: inject a ``client`` (any object exposing ``chat.completions.create``); in
production it lazily builds ``openai.OpenAI`` which reads ``OPENAI_API_KEY`` from the environment.
"""

from __future__ import annotations

REFINER_SYSTEM = (
    "You are a precise editor for a brainstorming tool. You receive a brainstorm PROMPT and a set "
    "of CANDIDATE IDEAS generated by another model, then return the same ideas with sharper, more "
    "concrete wording.\n"
    "Hard rules — never break them:\n"
    "1. Keep each idea's underlying CONCEPT exactly. Do not change what the idea is about.\n"
    "2. Do not merge, split, add, drop, or REORDER ideas — same count, same order.\n"
    "3. Do not make the ideas more similar to one another; preserve their DISTINCTNESS.\n"
    "4. Only tighten prose and add at most one concrete detail per idea; keep similar length.\n"
    "Return only the ideas, in the same format and order you received them — no preamble."
)


class OpenAIRefiner:
    """Polish steered candidates with an OpenAI chat model, concept-frozen.

    ``client`` is injectable for offline tests; left as ``None`` it lazily constructs
    ``openai.OpenAI(api_key=...)`` on first use (``api_key=None`` -> the SDK reads
    ``OPENAI_API_KEY`` from the environment).
    """

    def __init__(
        self,
        *,
        model: str = "gpt-4o-mini",
        temperature: float = 0.3,
        timeout: float = 60.0,
        api_key: str | None = None,
        system: str = REFINER_SYSTEM,
        client=None,
    ):
        self.model = model
        self.temperature = temperature
        self.timeout = timeout
        self.api_key = api_key
        self.system = system
        self._client = client

    def _get_client(self):
        if self._client is None:
            from openai import OpenAI  # lazy: only needed for a real call

            self._client = OpenAI(api_key=self.api_key, timeout=self.timeout)
        return self._client

    def refine(self, prompt: str, candidates: str) -> str:
        """Return the candidate ideas rewritten for clarity, concept-frozen."""
        user = f"PROMPT:\n{prompt}\n\nCANDIDATE IDEAS:\n{candidates}"
        resp = self._get_client().chat.completions.create(
            model=self.model,
            temperature=self.temperature,
            messages=[
                {"role": "system", "content": self.system},
                {"role": "user", "content": user},
            ],
        )
        return resp.choices[0].message.content or ""

    def info(self) -> dict:
        """Serialisable provenance for the /health + /package endpoints (no secrets)."""
        return {"model": self.model, "temperature": self.temperature}
