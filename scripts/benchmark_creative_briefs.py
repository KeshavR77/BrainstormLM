#!/usr/bin/env python3
"""Head-to-head creative-brief benchmark.

For each prompt in ``config/benchmark_creative_briefs.json``, generates N
outputs from each of three arms:

  - **gpt-4o** — frontier-tier OpenAI baseline
  - **gpt-4o-mini** — cost-efficient OpenAI baseline
  - **conceptial-3b** — Qwen2.5-3B + v17 steering + cognitive anti-mode
    + 3-shot persistent IdeaMemoryStore

Computes per-prompt + aggregate metrics:

  - **Vendi score** (MiniLM-L6-v2 embeddings) — higher is more diverse
  - **Near-duplicate rate** at cosine ≥ 0.92
  - **Distinct-2** — lexical bigram diversity

Then runs GPT-4o-mini scoring (composite + creativity + coherence + specificity
+ on_topic) over every output and aggregates.

Writes results to ``artifacts/benchmark_v2/`` as JSON + Markdown.

Usage::

    uv run python scripts/benchmark_creative_briefs.py \\
        --n 8 \\
        --arms gpt-4o,gpt-4o-mini,conceptial-3b \\
        --out artifacts/benchmark_v2/run_$(date +%Y%m%d_%H%M)

    # Skip the local model arm (faster, OpenAI-only baselines):
    uv run python scripts/benchmark_creative_briefs.py \\
        --arms gpt-4o,gpt-4o-mini --n 8

    # Skip arms you've already generated by passing --skip-existing
    uv run python scripts/benchmark_creative_briefs.py --skip-existing
"""

from __future__ import annotations

import argparse
import json
import sys
import time
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import numpy as np  # noqa: E402

from brainstormlm.clients.openai import complete as openai_complete  # noqa: E402


# ─── Generation helpers ──────────────────────────────────────────────────────


def _gpt_output(model: str, brief: str, k: int) -> str:
    """One GPT call. Asks for a single concept direction with a name + body."""
    system = (
        "You are a brand creative director. When given a brief, respond with ONE "
        "concept direction: a memorable 2-6 word name as the first line, then a "
        "one-paragraph body describing the concrete details. No preamble, no "
        "alternatives — just the single direction."
    )
    text, _usage = openai_complete(
        system=system,
        messages=[{"role": "user", "content": brief + f" (sample {k+1})"}],
        model=model,
        max_tokens=350,
        temperature=1.0,
        use_cache=False,
    )
    return text.strip()


def generate_gpt_arm(model: str, brief: str, n: int) -> list[dict]:
    out: list[dict] = []
    for k in range(n):
        try:
            text = _gpt_output(model, brief, k)
        except Exception as e:
            text = f"[generation failed: {e}]"
        out.append(
            {
                "model": model,
                "k": k,
                "text": text,
                "trajectory_id": uuid.uuid4().hex,
            }
        )
    return out


_CONCEPTIAL_ENGINE_CACHE: dict[str, object] = {}


def _get_conceptial_engine():
    """Load the v17 Conceptial steering engine once and cache it."""
    if "engine" in _CONCEPTIAL_ENGINE_CACHE:
        return _CONCEPTIAL_ENGINE_CACHE["engine"]

    from brainstormlm.conceptial.engine.config import SteeringConfig
    from brainstormlm.conceptial.engine.corpius import (
        apply_corpius_1,
        load_corpius_spec,
    )
    from brainstormlm.conceptial.engine.pipeline import SteeringEngine

    config_path = ROOT / "config" / "conceptial.json"
    spec = load_corpius_spec(config_path)
    cfg = SteeringConfig(model_id=spec.base_model)
    engine = SteeringEngine(cfg)
    apply_corpius_1(engine, spec)
    _CONCEPTIAL_ENGINE_CACHE["engine"] = engine
    _CONCEPTIAL_ENGINE_CACHE["spec"] = spec
    return engine


def generate_conceptial_arm(brief: str, n: int, project_id: str) -> list[dict]:
    """Generate via Conceptial 3B (local Qwen + v17 + anti-mode + persistent memory).

    Loads the model once per process via module-level cache (~30s cold start;
    ~5s/idea after).
    """
    from brainstormlm.conceptial.anti_mode import (
        extract_summary,
        format_anti_mode,
    )
    from brainstormlm.conceptial.idea_store import (
        SOURCE_GENERATED,
        IdeaMemoryStore,
    )

    import torch  # noqa: F401

    engine = _get_conceptial_engine()

    store = IdeaMemoryStore(db_path=ROOT / "data" / "benchmark_idea_memory.db")
    store.delete_project(project_id)
    HIDDEN_DIM = 64

    out: list[dict] = []
    prior_summaries: list[str] = []
    for k in range(n):
        # Always use anti-mode formatter — falls back to no-exclusion shape when
        # prior_summaries is empty, so this gives v17 + anti-mode uniformly.
        prompt = format_anti_mode(
            user_text=brief,
            prior_summaries=prior_summaries,
            exemplars=None,
            output_mode="generic",
        )
        temperature = 0.8 + (((k * 0.61803) % 1.0 - 0.5) * 0.1)  # ±0.05 jitter
        text = engine.complete(
            prompt,
            max_new_tokens=350,
            temperature=float(temperature),
            do_sample=True,
            do_steering=True,
            use_ghost_rejection=False,
        )
        text = text.strip()
        summary = extract_summary(text) or text.split("\n")[0][:80]
        prior_summaries.append(summary)
        idea_id = uuid.uuid4().hex
        store.add(
            project_id=project_id,
            idea_id=idea_id,
            hidden=torch.zeros(HIDDEN_DIM, dtype=torch.float32),
            text=text,
            source=SOURCE_GENERATED,
        )
        out.append(
            {
                "model": "conceptial-3b",
                "k": k,
                "text": text,
                "summary": summary,
                "trajectory_id": idea_id,
                "temperature": float(temperature),
            }
        )
    store.close()
    return out


# ─── Metrics ─────────────────────────────────────────────────────────────────


def _embed(texts: list[str]) -> np.ndarray:
    from creativity_evaluator.embeddings.local_embedder import LocalEmbedder

    embedder = LocalEmbedder("sentence-transformers/all-MiniLM-L6-v2")
    return np.asarray(embedder.embed(texts), dtype=np.float32)


def _vendi(vectors: np.ndarray) -> float:
    from creativity_evaluator.metrics.structural import vendi_score

    return float(vendi_score(vectors))


def _near_dup_rate(vectors: np.ndarray, thr: float = 0.92) -> float:
    """Pairs with cosine ≥ thr / total pairs."""
    if len(vectors) < 2:
        return 0.0
    v = vectors / (np.linalg.norm(vectors, axis=1, keepdims=True) + 1e-12)
    sim = v @ v.T
    n = len(vectors)
    iu = np.triu_indices(n, k=1)
    total = len(iu[0])
    if total == 0:
        return 0.0
    return float((sim[iu] >= thr).sum()) / float(total)


def _distinct_2(texts: list[str]) -> float:
    """Mean per-prompt distinct-2: unique bigrams / total bigrams across the set."""
    all_bigrams: list[tuple[str, str]] = []
    for t in texts:
        toks = t.lower().split()
        for i in range(len(toks) - 1):
            all_bigrams.append((toks[i], toks[i + 1]))
    if not all_bigrams:
        return 0.0
    return float(len(set(all_bigrams))) / float(len(all_bigrams))


# ─── Scoring ─────────────────────────────────────────────────────────────────


def _score_one(brief: str, text: str, model: str = "gpt-4o-mini") -> dict:
    """Score a single output on creativity / coherence / specificity / on_topic / composite."""
    system = (
        "You are a senior brand creative director scoring brainstormed concept "
        "directions. Score on four axes, each 1-5 (5 best). Composite is the mean. "
        "Return ONLY a JSON object with keys: creativity, coherence, specificity, "
        "on_topic, composite, rationale (one sentence). Do not add markdown fences."
    )
    user = f"Brief: {brief}\n\nDirection:\n{text}\n\nScore it."
    raw, _u = openai_complete(
        system=system,
        messages=[{"role": "user", "content": user}],
        model=model,
        max_tokens=200,
        temperature=0.0,
        use_cache=True,
    )
    raw = raw.strip()
    if raw.startswith("```"):
        raw = raw.strip("`")
        if raw.startswith("json"):
            raw = raw[4:]
    try:
        data = json.loads(raw)
    except Exception:
        return {
            "creativity": 0,
            "coherence": 0,
            "specificity": 0,
            "on_topic": 0,
            "composite": 0.0,
            "rationale": f"PARSE_ERROR: {raw[:120]}",
        }
    cre = float(data.get("creativity", 0))
    coh = float(data.get("coherence", 0))
    spe = float(data.get("specificity", 0))
    ont = float(data.get("on_topic", 0))
    comp = float(data.get("composite", (cre + coh + spe + ont) / 4))
    return {
        "creativity": cre,
        "coherence": coh,
        "specificity": spe,
        "on_topic": ont,
        "composite": comp,
        "rationale": str(data.get("rationale", "")),
    }


# ─── Runner ──────────────────────────────────────────────────────────────────


def load_conceptial_14b_cached(brief_id: str, n: int) -> list[dict]:
    """The 14B arm is generated separately on RunPod; we just read from disk.

    See ``scripts/runpod_batch_14b.py`` for the cloud-side generator.
    Returns the outputs list, trimmed to ``n`` entries.
    """
    cache_dir = ROOT / "artifacts" / "benchmark_v2" / "conceptial_14b_outputs"
    path = cache_dir / f"{brief_id}.conceptial-14b.json"
    if not path.exists():
        raise FileNotFoundError(
            f"No 14B outputs at {path}. Generate them on a RunPod A100 80GB "
            f"via `scripts/runpod_batch_14b.py`, then rsync the JSONs back to "
            f"{cache_dir.relative_to(ROOT)}/."
        )
    data = json.loads(path.read_text())
    outs = data.get("outputs", [])
    if len(outs) < n:
        raise ValueError(
            f"Only {len(outs)} 14B outputs found for {brief_id}; benchmark "
            f"wants N={n}. Regenerate via runpod_batch_14b.py with --n >= {n}."
        )
    return outs[:n]


def _arm_for(arm: str, brief: str, brief_id: str, n: int) -> list[dict]:
    if arm == "conceptial-3b":
        return generate_conceptial_arm(brief, n, project_id=f"bench-{brief_id}")
    if arm == "conceptial-14b":
        return load_conceptial_14b_cached(brief_id, n)
    return generate_gpt_arm(arm, brief, n)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=ROOT / "config" / "benchmark_creative_briefs.json")
    parser.add_argument(
        "--arms",
        default="gpt-4o,gpt-4o-mini,conceptial-3b",
        help="Comma-separated list of arms to run.",
    )
    parser.add_argument("--n", type=int, default=None, help="Override n per arm.")
    parser.add_argument("--out", type=Path, default=ROOT / "artifacts" / "benchmark_v2" / "run_latest")
    parser.add_argument("--skip-existing", action="store_true")
    parser.add_argument(
        "--limit-prompts",
        type=int,
        default=None,
        help="Limit to first N prompts (for fast smoke tests).",
    )
    parser.add_argument(
        "--skip-scoring",
        action="store_true",
        help="Generate outputs only; don't run GPT-4o-mini scoring.",
    )
    args = parser.parse_args()

    cfg = json.loads(args.config.read_text())
    prompts = cfg["prompts"]
    if args.limit_prompts:
        prompts = prompts[: args.limit_prompts]
    n = args.n or cfg["n_outputs_per_prompt"]
    arms = [a.strip() for a in args.arms.split(",") if a.strip()]
    args.out.mkdir(parents=True, exist_ok=True)
    print(f"Running {len(arms)} arms × {len(prompts)} prompts × N={n}")
    print(f"Output → {args.out}")

    # ── 1. Generate ───────────────────────────────────────────────────────────
    all_outputs: dict[str, dict[str, list[dict]]] = {}
    for p in prompts:
        pid = p["id"]
        print(f"\n[{pid}] {p['brief'][:80]}…")
        per_arm: dict[str, list[dict]] = {}
        for arm in arms:
            arm_out_path = args.out / f"{pid}.{arm}.json"
            if args.skip_existing and arm_out_path.exists():
                per_arm[arm] = json.loads(arm_out_path.read_text())["outputs"]
                print(f"  [{arm}] reused {len(per_arm[arm])} existing outputs")
                continue
            t0 = time.time()
            try:
                outs = _arm_for(arm, p["brief"], pid, n)
            except Exception as e:
                print(f"  [{arm}] FAILED: {e}")
                outs = []
            per_arm[arm] = outs
            arm_out_path.write_text(
                json.dumps({"prompt_id": pid, "arm": arm, "n": len(outs), "outputs": outs}, indent=2)
            )
            print(f"  [{arm}] generated {len(outs)} outputs in {time.time() - t0:.1f}s")
        all_outputs[pid] = per_arm

    # ── 2. Diversity metrics ──────────────────────────────────────────────────
    print("\n=== Diversity metrics ===")
    per_prompt_metrics: list[dict] = []
    for p in prompts:
        pid = p["id"]
        row = {"prompt_id": pid, "category": p["category"], "arms": {}}
        for arm in arms:
            outs = all_outputs.get(pid, {}).get(arm, [])
            texts = [o["text"] for o in outs if o.get("text")]
            if len(texts) < 2:
                row["arms"][arm] = {"vendi": None, "near_dup": None, "distinct_2": None, "n": len(texts)}
                continue
            vectors = _embed(texts)
            row["arms"][arm] = {
                "vendi": _vendi(vectors),
                "near_dup": _near_dup_rate(vectors),
                "distinct_2": _distinct_2(texts),
                "n": len(texts),
            }
        per_prompt_metrics.append(row)
        print(f"  [{pid}]")
        for arm in arms:
            m = row["arms"][arm]
            if m["vendi"] is None:
                print(f"    {arm:18s}: insufficient outputs")
            else:
                print(
                    f"    {arm:18s}: vendi={m['vendi']:.3f}  near_dup={m['near_dup']:.3f}  "
                    f"distinct_2={m['distinct_2']:.3f}"
                )

    # ── 3. Quality scoring ────────────────────────────────────────────────────
    quality: dict[str, dict[str, list[dict]]] = {}
    if not args.skip_scoring:
        print("\n=== Quality scoring (gpt-4o-mini judge) ===")
        for p in prompts:
            pid = p["id"]
            quality[pid] = {}
            for arm in arms:
                arm_scores: list[dict] = []
                for o in all_outputs.get(pid, {}).get(arm, []):
                    sc = _score_one(p["brief"], o["text"])
                    arm_scores.append(sc)
                quality[pid][arm] = arm_scores
            # Cheap log
            for arm in arms:
                scs = quality[pid][arm]
                if not scs:
                    continue
                comp = sum(s["composite"] for s in scs) / max(len(scs), 1)
                print(f"    [{pid:30s} | {arm:18s}] composite={comp:.2f}  n={len(scs)}")

    # ── 4. Aggregate ──────────────────────────────────────────────────────────
    aggregate: dict[str, dict] = {}
    for arm in arms:
        v_list: list[float] = []
        nd_list: list[float] = []
        d2_list: list[float] = []
        comp_list: list[float] = []
        cre_list: list[float] = []
        coh_list: list[float] = []
        spe_list: list[float] = []
        ont_list: list[float] = []
        for row in per_prompt_metrics:
            m = row["arms"][arm]
            if m["vendi"] is not None:
                v_list.append(m["vendi"])
                nd_list.append(m["near_dup"])
                d2_list.append(m["distinct_2"])
        for pid, arms_q in quality.items():
            for s in arms_q.get(arm, []):
                if s["composite"] > 0:
                    comp_list.append(s["composite"])
                    cre_list.append(s["creativity"])
                    coh_list.append(s["coherence"])
                    spe_list.append(s["specificity"])
                    ont_list.append(s["on_topic"])
        aggregate[arm] = {
            "mean_vendi": float(np.mean(v_list)) if v_list else None,
            "mean_near_dup": float(np.mean(nd_list)) if nd_list else None,
            "mean_distinct_2": float(np.mean(d2_list)) if d2_list else None,
            "mean_composite": float(np.mean(comp_list)) if comp_list else None,
            "mean_creativity": float(np.mean(cre_list)) if cre_list else None,
            "mean_coherence": float(np.mean(coh_list)) if coh_list else None,
            "mean_specificity": float(np.mean(spe_list)) if spe_list else None,
            "mean_on_topic": float(np.mean(ont_list)) if ont_list else None,
            "n_prompts": len(v_list),
            "n_outputs_total": len(comp_list) if comp_list else sum(m["n"] for m in (row["arms"][arm] for row in per_prompt_metrics) if m["n"]),
        }

    # ── 5. Write reports ──────────────────────────────────────────────────────
    summary_path = args.out / "SUMMARY.json"
    summary_path.write_text(
        json.dumps(
            {
                "config": cfg["name"],
                "n_per_arm_per_prompt": n,
                "arms": arms,
                "per_prompt": per_prompt_metrics,
                "aggregate": aggregate,
                "quality_per_prompt": quality,
            },
            indent=2,
        )
    )
    print(f"\n→ wrote {summary_path}")

    md_path = args.out / "RESULTS.md"
    lines: list[str] = []
    lines.append(f"# Head-to-head benchmark — {cfg['name']}")
    lines.append("")
    lines.append(f"**Generated:** {time.strftime('%Y-%m-%d %H:%M')}")
    lines.append("**Config:** `config/benchmark_creative_briefs.json`")
    lines.append(f"**N per arm per prompt:** {n}")
    lines.append(f"**Prompts:** {len(prompts)}")
    lines.append("")
    lines.append("## Aggregate (mean across all prompts)")
    lines.append("")
    lines.append("| Arm | Vendi | Near-dup | Distinct-2 | Composite | Creativity | Specificity | On-topic |")
    lines.append("|---|---:|---:|---:|---:|---:|---:|---:|")
    for arm in arms:
        a = aggregate[arm]
        def f(x: float | None, fmt: str = ".2f") -> str:
            return "—" if x is None else format(x, fmt)
        lines.append(
            f"| {arm} | {f(a['mean_vendi'], '.3f')} | {f(a['mean_near_dup'], '.3f')} | "
            f"{f(a['mean_distinct_2'], '.3f')} | {f(a['mean_composite'])} | "
            f"{f(a['mean_creativity'])} | {f(a['mean_specificity'])} | {f(a['mean_on_topic'])} |"
        )
    lines.append("")
    lines.append("## Per-prompt breakdown")
    lines.append("")
    lines.append("### Diversity (Vendi)")
    lines.append("")
    headers = ["prompt"] + [a for a in arms]
    lines.append("| " + " | ".join(headers) + " |")
    lines.append("|" + "|".join(["---"] * len(headers)) + "|")
    for row in per_prompt_metrics:
        cells = [row["prompt_id"]]
        for arm in arms:
            v = row["arms"][arm]["vendi"]
            cells.append("—" if v is None else f"{v:.3f}")
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("")
    md_path.write_text("\n".join(lines))
    print(f"→ wrote {md_path}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
